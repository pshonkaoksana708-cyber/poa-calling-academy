function createLevel(input: {
  slug: "basic" | "practice" | "pro";
  title: string;
  label: string;
  duration: string;
  price: string;
  description: string;
  result: string;
  moduleTitle: string;
  moduleDescription: string;
  lessons: typeof tourismBlock1Lessons;
}): ProfessionLevel {
  return {
    slug: input.slug,
    title: input.title,
    label: input.label,
    duration: input.duration,
    price: input.price,
    level: input.slug,
    description: input.description,
    result: input.result,
    learningResult: {
      skills: [
        "Понимать устройство туристической отрасли и роль специалиста по туризму.",
        "Подбирать направления, размещение, питание, логистику и туристический продукт под запрос клиента.",
        "Работать с клиентскими запросами, предложениями, бронированием и профессиональной коммуникацией.",
      ],
      tasks: [
        "Анализировать потребности туриста и формировать подходящие варианты путешествия.",
        "Проверять документы, правила въезда, условия размещения и логистику поездки.",
        "Готовить туристическое предложение и сопровождать клиента на ключевых этапах выбора.",
      ],
      workplaces: [
        "Туристические агентства и сервисные компании.",
        "Команды продаж и клиентского сопровождения в туризме.",
        "Самостоятельная практика специалиста по подбору путешествий.",
      ],
    },
    modules: [
      {
        id: `tourism-${input.slug}-module`,
        title: input.moduleTitle,
        description: input.moduleDescription,
        lessons: input.lessons.map((lesson) => ({
          id: `tourism-${input.slug}-lesson-${lesson.lessonNumber}`,
          title: lesson.title,
          duration: "Самостоятельное изучение",
          content: [
            "Полный материал урока открыт отдельной страницей образовательной программы.",
            `Маршрут: ${
              input.slug === "basic"
                ? `/course/tourism/basic/lesson-${lesson.lessonNumber}`
                : input.slug === "practice"
                  ? `/course/tourism/basic/block-2/lesson-${lesson.lessonNumber}`
                  : `/course/tourism/basic/block-3/lesson-${lesson.lessonNumber}`
            }`,
          ],
        })),
      },
    ],
  };
}

