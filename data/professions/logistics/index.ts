function createLevel(input: {
  slug: "basic" | "practice" | "pro";
  title: string;
  label: string;
  duration: string;
  description: string;
  result: string;
  moduleTitle: string;
  moduleDescription: string;
  lessons: typeof logisticsBlock1Lessons;
}): ProfessionLevel {
  return {
    slug: input.slug,
    title: input.title,
    label: input.label,
    duration: input.duration,
    price:
      input.slug === "basic"
        ? "6 900 ₽"
        : input.slug === "practice"
          ? "12 900 ₽"
          : "18 900 ₽",
    level: input.slug,
    description: input.description,
    result: input.result,
    learningResult: {
      skills: [
        "Понимать логику международных перевозок и роль логиста в цепочке поставок.",
        "Работать с документами, участниками внешнеэкономической деятельности и контрольными точками перевозки.",
        "Оценивать риски, сроки, стоимость и качество логистических процессов.",
      ],
      tasks: [
        "Собрать вводные данные по международной перевозке.",
        "Определить участников процесса и необходимые документы.",
        "Контролировать этапы доставки, сроки, коммуникацию и возможные отклонения.",
      ],
      workplaces: [
        "Логистические и транспортно-экспедиционные компании.",
        "Отделы внешнеэкономической деятельности и международных поставок.",
        "Производственные, торговые и e-commerce компании с международной логистикой.",
      ],
    },
    modules: [
      {
        id: `logistics-${input.slug}-module`,
        title: input.moduleTitle,
        description: input.moduleDescription,
        lessons: input.lessons.map((lesson) => ({
          id: `logistics-${input.slug}-lesson-${lesson.lessonNumber}`,
          title: lesson.title,
          duration: "Самостоятельное изучение",
          content: [
            "Полный материал урока открыт отдельной страницей образовательной программы.",
            `Маршрут: ${
              input.slug === "basic"
                ? `/course/logistics/basic/lesson-${lesson.lessonNumber}`
                : input.slug === "practice"
                  ? `/course/logistics/basic/block-2/lesson-${lesson.lessonNumber}`
                  : `/course/logistics/basic/block-3/lesson-${lesson.lessonNumber}`
            }`,
          ],
        })),
      },
    ],
  };
}

