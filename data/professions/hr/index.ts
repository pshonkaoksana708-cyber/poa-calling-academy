function createLevel(input: {
  slug: "basic" | "practice" | "pro";
  title: string;
  label: string;
  duration: string;
  price: string;
  description: string;
  result: string;
  moduleTitle: string;
  moduleDescription: string;
  lessons: typeof hrBlock1Lessons;
}): ProfessionLevel {
  return {
    slug: input.slug,
    title: input.title,
    label: input.label,
    duration: input.duration,
    price: input.price,
    level: input.slug,
    description: input.description,
    result: input.result,
    learningResult: {
      skills: [
        "Понимать задачи специалиста по кадрам и управлению персоналом.",
        "Работать с вакансиями, резюме, интервью и оценкой кандидатов.",
        "Выстраивать адаптацию, развитие сотрудников и понятную HR-коммуникацию.",
      ],
      tasks: [
        "Формулировать потребность в сотруднике и портрет кандидата.",
        "Проводить первичный отбор, интервью и оценку кандидатов.",
        "Разбирать рабочие HR-ситуации и принимать профессиональные решения.",
      ],
      workplaces: [
        "Отдел кадров и персонала.",
        "Команды подбора, адаптации и развития сотрудников.",
        "Малый и средний бизнес, где специалист ведет HR-процессы.",
      ],
    },
    modules: [
      {
        id: `hr-${input.slug}-module`,
        title: input.moduleTitle,
        description: input.moduleDescription,
        lessons: input.lessons.map((lesson) => ({
          id: `hr-${input.slug}-lesson-${lesson.lessonNumber}`,
          title: lesson.title,
          duration: "Самостоятельное изучение",
          content: [
            "Полный материал урока открыт отдельной страницей образовательной программы.",
            `Маршрут: ${
              input.slug === "basic"
                ? `/course/hr/basic/lesson-${lesson.lessonNumber}`
                : input.slug === "practice"
                  ? `/course/hr/basic/block-2/lesson-${lesson.lessonNumber}`
                  : `/course/hr/basic/block-3/lesson-${lesson.lessonNumber}`
            }`,
          ],
        })),
      },
    ],
  };
}

