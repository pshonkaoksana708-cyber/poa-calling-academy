import type { Assessment, AssessmentQuestion } from "@/data/assessments/types";

function option(id: string, text: string) {
  return { id, text };
}

function question(
  id: string,
  text: string,
  correctAnswer: string,
  explanation: string,
  options: [string, string, string, string],
): AssessmentQuestion {
  return {
    id,
    type: "single-choice",
    text,
    options: [
      option("a", options[0]),
      option("b", options[1]),
      option("c", options[2]),
      option("d", options[3]),
    ],
    correctAnswer,
    explanation,
    points: 1,
  };
}

